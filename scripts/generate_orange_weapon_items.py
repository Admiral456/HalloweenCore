#!/usr/bin/env python3
"""Generate orange weapon item definitions for ItemsAdder's modern graphics system.

Requires ItemsAdder 4.0.13+ and Minecraft 1.21.4+ on both server and clients.
The generator uses vanilla textures as bases and applies a color tint, so it does
not create, bundle, or redistribute any texture PNG files.
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "itemsadder/contents/warriorland_halloween/configs/orange_weapons.yml"
COLOR = "#ff7900"
WEAPONS = [
    ("orange_trident", "Halloweenový trojzubec", "TRIDENT", "trident"),
    ("orange_mace", "Halloweenový palcát", "MACE", "mace"),
    ("orange_netherite_sword", "Halloweenový netheritový meč", "NETHERITE_SWORD", "netherite_sword"),
    ("orange_netherite_axe", "Halloweenová netheritová sekera", "NETHERITE_AXE", "netherite_axe"),
    ("orange_netherite_spear", "Halloweenové netheritové kopí", "NETHERITE_SPEAR", "netherite_spear"),
]


def render_config() -> str:
    lines = [
        "# Generated by scripts/generate_orange_weapon_items.py; do not edit by hand.",
        "# Uses vanilla base textures tinted orange by ItemsAdder; no custom PNGs required.",
        "info:",
        "  namespace: warriorland_halloween",
        "",
        "items:",
    ]
    for item_id, name, material, texture in WEAPONS:
        lines.extend([
            f"  {item_id}:",
            f'    name: "&6&l{name}"',
            "    lore:",
            '      - "&7Oranžová halloweenská zbraň."',
            '      - "&8HalloweenCore"',
            f"    material: {material}",
            "    graphics:",
            f"      texture: minecraft:item/{texture}",
            f'      color: "{COLOR}"',
            "",
        ])
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="Output YAML path (defaults to HalloweenCore's ItemsAdder content folder).")
    parser.add_argument("--check", action="store_true",
                        help="Check that the generated file is current without writing it.")
    args = parser.parse_args()
    expected = render_config()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            parser.exit(1, f"Orange weapon config is missing or out of date: {args.output}\n")
        print(f"Orange weapon config is current: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Generated {len(WEAPONS)} orange weapon definitions: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
